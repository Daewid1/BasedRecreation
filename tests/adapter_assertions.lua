
B.Config.init()
local adapter = B.HussUI
local tab = adapter:CreateTab("Combat", "swords", "Test")
tab:AddSection("Protection")
local calls = 0
local switch = tab:AddToggle({ Text = "Dodge", Flag = "autoDodge", Default = false, Callback = function() calls += 1 end })
assert(switch.Value == false and calls == 1)
switch.Set(true)
assert(switch.Value == true and B.Config.get("autoDodge") == true and calls == 2)
B.Config.set("autoDodge", false)
assert(switch.Value == false and calls == 3)
local slider = tab:AddSlider({ Text = "Range", Flag = "range", Min = 8, Max = 80, Increment = 0.5, Default = 45 })
slider.Set(200)
assert(slider.Value == 80)
slider.Set(12.3)
assert(slider.Value == 12.5)
assert(not pcall(slider.Set, 0 / 0))
assert(not pcall(slider.Set, math.huge))
local dropdown = tab:AddDropdown({ Text = "Mode", Flag = "mode", Options = { "A", "B" }, Default = "A" })
assert(not pcall(dropdown.Set, "invalid"))
dropdown.Set("B")
assert(dropdown.Value == "B")
local pressed = 0
local key = tab:AddKeybind({ Text = "Action", Flag = "teleportKey", Default = Enum.KeyCode.T, Pressed = function() pressed += 1 end })
assert(key.Value == Enum.KeyCode.T)
assert(B.Config.bindOf("huss.action.teleportKey").key == "T")
key.Set(Enum.KeyCode.H)
assert(B.Config.bindOf("huss.action.teleportKey").key == "H")
B.Config.bind("huss.action.teleportKey", "K")
assert(key.Value == Enum.KeyCode.K)
B.Config.bind("huss.action.teleportKey", nil)
assert(key.Value == Enum.KeyCode.Unknown)
local dodgeKey = tab:AddKeybind({ Text = "Dodge key", Flag = "autoDodgeKey", Default = Enum.KeyCode.G, Pressed = function() error("must not install a duplicate action") end })
assert(B.Config.bindOf("autoDodge").key == "G")
assert(not B.Config.isAction("autoDodge"))
B.Config.listen()
B.S.UserInputService.InputBegan.callback({ UserInputType = "Keyboard", KeyCode = Enum.KeyCode.G }, false)
assert(switch.Value == true)
B.Config.saveAs("test")
switch.Set(false)
B.Config.load("test")
assert(switch.Value == false)
files["config/other.json"] = { values = { autoDodge = true, range = 19 } }
B.Config.load("other")
assert(switch.Value == true and slider.Value == 19)
tab:AddDisclosure("Advanced")
tab:AddToggle({ Text = "Nested", Flag = "nested", Default = false })
assert(tab.sections[1].rows[#tab.sections[1].rows].kind == "disclosure")
assert(#tab.sections[1].rows[#tab.sections[1].rows].spec.rows == 1)
local before = calls
B.Config.set("autoDodge", true)
assert(calls == before)
print("PASS adapter: defaults, callbacks, validation, key ownership, rebind, unbind, profiles, disclosure")

